"""Generate src/FullModPanel.Core/PinyinTable.g.cs from pypinyin.

Dev-time only. The mod does not run Python. Re-run this when the table needs
changing, from the repository root:

    python -m venv <venv>
    <venv>/Scripts/pip install pypinyin
    <venv>/Scripts/python tools/gen_pinyin.py

Each code point from U+3400 to U+9FFF gets one entry, separated by '|'. An entry is
the toneless primary reading (for example "hai"), or empty when the character has
no reading. Lookup is entry[codePoint - FirstCodePoint].
"""

import pathlib
import re

from pypinyin import Style, pinyin

FIRST = 0x3400
LAST = 0x9FFF
CJK_RANGES = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF)]
ASCII_SYLLABLE = re.compile(r"^[a-z]+$")
ENTRIES_PER_LINE = 120

OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "FullModPanel.Core" / "PinyinTable.g.cs"


def in_cjk(cp: int) -> bool:
    return any(lo <= cp <= hi for lo, hi in CJK_RANGES)


def reading(cp: int) -> str:
    if not in_cjk(cp):
        return ""
    value = pinyin(chr(cp), style=Style.NORMAL, heteronym=False, errors="ignore")
    if not value or not value[0]:
        return ""
    syllable = value[0][0].lower()
    return syllable if ASCII_SYLLABLE.match(syllable) else ""


def main() -> None:
    entries = [reading(cp) for cp in range(FIRST, LAST + 1)]
    with_reading = sum(1 for entry in entries if entry)

    lines = []
    for start in range(0, len(entries), ENTRIES_PER_LINE):
        chunk = "|".join(entries[start:start + ENTRIES_PER_LINE])
        if start + ENTRIES_PER_LINE < len(entries):
            chunk += "|"
        lines.append(f'        "{chunk}"')

    body = " +\n".join(lines)
    FIRST_HEX = hex(FIRST)
    text = f"""// <auto-generated>
// Generated by tools/gen_pinyin.py from pypinyin. Do not edit by hand.
// Covers U+3400..U+4DBF and U+4E00..U+9FFF. {with_reading} characters have a reading.
// </auto-generated>

namespace FullModPanel.Core;

internal static class PinyinTable
{{
    /// <summary>Code point of the first entry in <see cref="Readings"/>.</summary>
    internal const int FirstCodePoint = {FIRST_HEX};

    /// <summary>
    /// Pipe-separated toneless readings for U+3400..U+9FFF. An empty entry means no reading.
    /// </summary>
    internal const string Readings =
{body};
}}
"""
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(entries)} entries, {with_reading} with a reading)")


if __name__ == "__main__":
    main()
